  function atomById(id) {
    for (var i = 0; i < ATOMS.length; i++) if (ATOMS[i].id === id) return ATOMS[i];
    return null;
  }

  function pickedAtoms() {
    var out = [];
    SLOTS.forEach(function (s) {
      var a = recipe.picks[s.id] ? atomById(recipe.picks[s.id]) : null;
      if (a) out.push(a);
    });
    return out;
  }

  function assemble() {
    var baseEn = [recipe.subject, recipe.action, recipe.scene].filter(Boolean).join(' ');
    var partsEn = pickedAtoms().map(function (a) { return a.en; });
    var en = (baseEn ? baseEn + ', ' : '') + partsEn.join(', ');
    var baseZh = recipe.subject + (recipe.action || '') + (recipe.scene ? '，' + recipe.scene : '');
    var partsZh = pickedAtoms().map(function (a) { return slotName(slotOf(a)) + '：' + a.zh; });
    var zh = (baseZh ? baseZh + '。' : '') + partsZh.join('，') + (partsZh.length ? '。' : '');
    var atoms = pickedAtoms();
    var score = atoms.length ? Math.round(atoms.reduce(function (s, a) { return s + a.score; }, 0) / atoms.length) : 0;
    return { en: en || '—', zh: zh || '—', score: score, atoms: atoms };
  }
  function slotOf(a) {
    for (var i = 0; i < SLOTS.length; i++) if (SLOTS[i].id === a.slot) return SLOTS[i];
    return { zh: a.slot, en: a.slot, desc: '', descEn: '' };
  }

  function cardText(a) {
    var lines = [];
    lines.push('🎬 ' + t('card-brand'));
    if (recipe.subject) lines.push(t('f-subject') + '：' + recipe.subject);
    if (recipe.action) lines.push(t('f-action') + '：' + recipe.action);
    if (recipe.scene) lines.push(t('f-scene') + '：' + recipe.scene);
    a.atoms.forEach(function (x) { lines.push(slotName(slotOf(x)) + '：' + atomName(x) + '（' + x.en + '）'); });
    lines.push(t('card-score') + '：' + a.score + '/100 · ' + t('card-slots') + '：' + a.atoms.length + '/' + SLOTS.length);
    lines.push('—— ' + t('brand') + ' Visual Prompt Atlas');
    return lines.join('\n');
  }

  function gradClass() {
    var color = recipe.picks.color ? atomById(recipe.picks.color) : null;
    if (color) {
      var map = {
        'cyberpunk-palette': 'grad-cyberpunk', monochrome: 'grad-mono', pastel: 'grad-pastel',
        'high-sat': 'grad-vivid', desaturated: 'grad-desat', 'teal-orange': 'grad-teal'
      };
      if (map[color.id]) return map[color.id];
    }
    var time = recipe.picks.time ? atomById(recipe.picks.time) : null;
    if (time) {
      var tmap = { dawn: 'grad-dawn', dusk: 'grad-dusk', 'blue-hour': 'grad-blue-hour', night: 'grad-night', 'rainy-night': 'grad-rainy-night' };
      if (tmap[time.id]) return tmap[time.id];
    }
    return 'grad-default';
  }

  function renderPreview() {
    var box = $('card-preview');
    var a = assemble();
    var hasAny = recipe.subject || recipe.action || recipe.scene || a.atoms.length > 0;
    if (!hasAny) {
      box.innerHTML = '<div class="card-empty">' + t('card-empty') + '</div>';
    } else {
      var midMain = (recipe.subject ? recipe.subject + ' ' : '') + (recipe.action ? recipe.action : '') + (recipe.scene ? ' @ ' + recipe.scene : '');
      var chipsHtml = a.atoms.map(function (x) { return '<span class="cc">' + atomName(x) + '</span>'; }).join('');
      box.innerHTML =
        '<div class="card-stage ' + gradClass() + '">' +
        '<div class="card-top"><span class="card-brand">' + t('card-brand') + '</span>' +
        '<span class="card-scorepill">' + a.score + '/100</span></div>' +
        '<div class="card-mid"><div class="card-main">' + midMain +
        '<small>' + t('card-score') + ': ' + a.score + '/100 · ' + t('card-slots') + ': ' + a.atoms.length + '/' + SLOTS.length + '</small></div>' +
        '<span class="card-img-note">' + t('card-img-note') + '</span></div>' +
        '<div class="card-chips">' + chipsHtml + '</div>' +
        '</div>' +
        '<div class="card-foot"><span>' + t('card-score') + '</span><b>' + a.score + '/100</b></div>';
    }
    $('prompt-en').textContent = a.en;
    $('prompt-zh').textContent = a.zh;
    $('prompt-card').textContent = cardText(a);
  }

  function randomRecipe() {
    var s = SAMPLES[lang] || SAMPLES.zh;
    function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
    recipe.subject = pick(s.subjects);
    recipe.action = pick(s.actions);
    recipe.scene = pick(s.scenes);
    recipe.picks = {};
    SLOTS.forEach(function (slot) {
      var list = BY_SLOT[slot.id] || [];
      if (list.length) recipe.picks[slot.id] = list[Math.floor(Math.random() * list.length)].id;
    });
    $('recipe-subject').value = recipe.subject;
    $('recipe-action').value = recipe.action;
    $('recipe-scene').value = recipe.scene;
    renderPickers();
    renderPreview();
  }
  function resetRecipe() {
    recipe = { subject: '', action: '', scene: '', picks: {} };
    $('recipe-subject').value = '';
    $('recipe-action').value = '';
    $('recipe-scene').value = '';
    renderPickers();
    renderPreview();
  }

